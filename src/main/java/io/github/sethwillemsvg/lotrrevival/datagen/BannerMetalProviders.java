package io.github.sethwillemsvg.lotrrevival.datagen;

import io.github.sethwillemsvg.lotrrevival.LOTRRevival;
import io.github.sethwillemsvg.lotrrevival.core.metal.BannerMetals;
import java.util.List;
import java.util.Set;
import java.util.concurrent.CompletableFuture;
import net.minecraft.core.HolderLookup;
import net.minecraft.data.CachedOutput;
import net.minecraft.data.DataProvider;
import net.minecraft.data.PackOutput;
import net.minecraft.data.loot.BlockLootSubProvider;
import net.minecraft.data.loot.LootTableProvider;
import net.minecraft.data.recipes.RecipeCategory;
import net.minecraft.data.recipes.RecipeOutput;
import net.minecraft.data.recipes.RecipeProvider;
import net.minecraft.data.recipes.ShapedRecipeBuilder;
import net.minecraft.data.recipes.ShapelessRecipeBuilder;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.flag.FeatureFlags;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.storage.loot.parameters.LootContextParamSets;
import net.neoforged.neoforge.client.model.generators.BlockStateProvider;
import net.neoforged.neoforge.client.model.generators.ItemModelProvider;
import net.neoforged.neoforge.client.model.generators.ModelFile;
import net.neoforged.neoforge.common.data.BlockTagsProvider;
import net.neoforged.neoforge.common.data.ExistingFileHelper;
import net.neoforged.neoforge.data.event.GatherDataEvent;

/** Core #105: datagen for the bronze and silver ingots and storage blocks. */
final class BannerMetalProviders {
    private BannerMetalProviders() {}

    static void gather(GatherDataEvent event) {
        PackOutput output = event.getGenerator().getPackOutput();
        CompletableFuture<HolderLookup.Provider> lookup = event.getLookupProvider();
        ModLangProvider.contribute(lang -> {
            lang.add(BannerMetals.BRONZE_INGOT.get(), "Bronze Ingot");
            lang.add(BannerMetals.SILVER_INGOT.get(), "Silver Ingot");
            lang.add(BannerMetals.BRONZE_BLOCK.get(), "Block of Bronze");
            lang.add(BannerMetals.SILVER_BLOCK.get(), "Block of Silver");
        });
        event.getGenerator()
                .addProvider(event.includeClient(), new ItemModels(output, event.getExistingFileHelper()));
        event.getGenerator()
                .addProvider(event.includeClient(), new BlockStates(output, event.getExistingFileHelper()));
        event.getGenerator()
                .addProvider(event.includeServer(), new Named("Banner metal recipes", new Recipes(output, lookup)));
        event.getGenerator()
                .addProvider(event.includeServer(), new Named("Banner metal loot tables", new Loot(output, lookup)));
        event.getGenerator().addProvider(event.includeServer(), new Tags(output, lookup, event.getExistingFileHelper()));
    }

    /** Vanilla recipe and loot providers have a final getName(); this gives them a unique one. */
    private record Named(String name, DataProvider delegate) implements DataProvider {
        @Override
        public CompletableFuture<?> run(CachedOutput cache) {
            return delegate.run(cache);
        }

        @Override
        public String getName() {
            return name;
        }
    }

    static final class ItemModels extends ItemModelProvider {
        ItemModels(PackOutput output, ExistingFileHelper helper) {
            super(output, LOTRRevival.MOD_ID, helper);
        }

        @Override
        protected void registerModels() {
            basicItem(BannerMetals.BRONZE_INGOT.get());
            basicItem(BannerMetals.SILVER_INGOT.get());
            // Block models are generated by BlockStates in the same run, so they are not "existing" yet.
            getBuilder("bronze_block").parent(new ModelFile.UncheckedModelFile(LOTRRevival.id("block/bronze_block")));
            getBuilder("silver_block").parent(new ModelFile.UncheckedModelFile(LOTRRevival.id("block/silver_block")));
        }

        @Override
        public String getName() {
            return "Banner metal item models";
        }
    }

    static final class BlockStates extends BlockStateProvider {
        BlockStates(PackOutput output, ExistingFileHelper helper) {
            super(output, LOTRRevival.MOD_ID, helper);
        }

        @Override
        protected void registerStatesAndModels() {
            simpleBlock(BannerMetals.BRONZE_BLOCK.get());
            simpleBlock(BannerMetals.SILVER_BLOCK.get());
        }

        @Override
        public String getName() {
            return "Banner metal block states";
        }
    }

    static final class Recipes extends RecipeProvider {
        Recipes(PackOutput output, CompletableFuture<HolderLookup.Provider> registries) {
            super(output, registries);
        }

        @Override
        protected void buildRecipes(RecipeOutput out) {
            storage(out, BannerMetals.BRONZE_INGOT.get(), BannerMetals.BRONZE_BLOCK.get(), "bronze");
            storage(out, BannerMetals.SILVER_INGOT.get(), BannerMetals.SILVER_BLOCK.get(), "silver");
        }

        private void storage(RecipeOutput out, Item ingot, Block block, String name) {
            ShapedRecipeBuilder.shaped(RecipeCategory.BUILDING_BLOCKS, block)
                    .pattern("III")
                    .pattern("III")
                    .pattern("III")
                    .define('I', ingot)
                    .unlockedBy("has_" + name + "_ingot", has(ingot))
                    .save(out, ResourceLocation.fromNamespaceAndPath(LOTRRevival.MOD_ID, name + "_block_from_ingots"));
            ShapelessRecipeBuilder.shapeless(RecipeCategory.MISC, ingot, 9)
                    .requires(block)
                    .unlockedBy("has_" + name + "_block", has(block))
                    .save(out, ResourceLocation.fromNamespaceAndPath(LOTRRevival.MOD_ID, name + "_ingots_from_block"));
        }
    }

    static final class Loot extends LootTableProvider {
        Loot(PackOutput output, CompletableFuture<HolderLookup.Provider> registries) {
            super(
                    output,
                    Set.of(),
                    List.of(new SubProviderEntry(BlockLoot::new, LootContextParamSets.BLOCK)),
                    registries);
        }
    }

    private static final class BlockLoot extends BlockLootSubProvider {
        BlockLoot(HolderLookup.Provider registries) {
            super(Set.<Item>of(), FeatureFlags.REGISTRY.allFlags(), registries);
        }

        @Override
        protected void generate() {
            dropSelf(BannerMetals.BRONZE_BLOCK.get());
            dropSelf(BannerMetals.SILVER_BLOCK.get());
        }

        @Override
        protected Iterable<Block> getKnownBlocks() {
            return List.of(BannerMetals.BRONZE_BLOCK.get(), BannerMetals.SILVER_BLOCK.get());
        }
    }

    static final class Tags extends BlockTagsProvider {
        Tags(PackOutput output, CompletableFuture<HolderLookup.Provider> lookup, ExistingFileHelper helper) {
            super(output, lookup, LOTRRevival.MOD_ID, helper);
        }

        @Override
        protected void addTags(HolderLookup.Provider provider) {
            tag(net.minecraft.tags.BlockTags.MINEABLE_WITH_PICKAXE)
                    .add(BannerMetals.BRONZE_BLOCK.get())
                    .add(BannerMetals.SILVER_BLOCK.get());
            tag(net.minecraft.tags.BlockTags.NEEDS_STONE_TOOL)
                    .add(BannerMetals.BRONZE_BLOCK.get())
                    .add(BannerMetals.SILVER_BLOCK.get());
        }

        @Override
        public String getName() {
            return "Banner metal block tags";
        }
    }
}

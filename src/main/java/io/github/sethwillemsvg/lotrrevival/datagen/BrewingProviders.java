import net.minecraft.tags.ItemTags;
import net.minecraft.world.item.Items;
import net.neoforged.neoforge.client.model.generators.ItemModelProvider;
import net.neoforged.neoforge.common.data.ExistingFileHelper;

/** Core: brewing datagen (item models, block states, loot, tags and recipes). */
final class BrewingProviders {
    private BrewingProviders() {}

    static final class ItemModels extends ItemModelProvider {
        ItemModels(PackOutput output, ExistingFileHelper existingFileHelper) {
            super(output, LOTRRevival.MOD_ID, existingFileHelper);
        }

        @Override
        protected void registerModels() {
            basicItem(BrewingItems.WOODEN_MUG.get());
            BrewingItems.DRINKS.forEach(drink -> basicItem(drink.get()));
            // The block model is generated by BlockStates in the same run, so it is not "existing" yet.
            getBuilder("brewing_barrel")
                    .parent(new ModelFile.UncheckedModelFile(LOTRRevival.id("block/brewing_barrel")));
        }
    }

    static final class BlockStates extends BlockStateProvider {
        BlockStates(PackOutput output, ExistingFileHelper existingFileHelper) {
            super(output, LOTRRevival.MOD_ID, existingFileHelper);
        }

        @Override
        protected void registerStatesAndModels() {
            ModelFile model = models().orientableWithBottom(
                    "brewing_barrel",
                    modLoc("block/brewing_barrel_side"),
                    modLoc("block/brewing_barrel_front"),
                    modLoc("block/brewing_barrel_top"),
                    modLoc("block/brewing_barrel_top"));
            horizontalBlock(BrewingBlocks.BARREL.get(), model);
        }

        @Override
        public String getName() {
            return "Brewing block states";
        }
    }

    /** The barrel drops itself with its brew and custom name; no explosion condition. */
    static final class Loot extends LootTableProvider {
        Loot(PackOutput output, CompletableFuture<HolderLookup.Provider> registries) {
            super(output, Set.of(), List.of(new SubProviderEntry(BarrelLoot::new, LootContextParamSets.BLOCK)), registries);
        }
    }

    private static final class BarrelLoot implements LootTableSubProvider {
        BarrelLoot(HolderLookup.Provider registries) {}

        @Override
        public void generate(BiConsumer<ResourceKey<LootTable>, LootTable.Builder> output) {
            Block barrel = BrewingBlocks.BARREL.get();
            output.accept(
                    barrel.getLootTable(),
                    LootTable.lootTable()
                            .withPool(LootPool.lootPool()
                                    .setRolls(ConstantValue.exactly(1))
                                    .add(LootItem.lootTableItem(barrel)
                                            .apply(CopyComponentsFunction.copyComponents(
                                                            CopyComponentsFunction.Source.BLOCK_ENTITY)
                                                    .include(BrewingComponents.BARREL_BREW.get())
                                                    .include(DataComponents.CUSTOM_NAME)
                                                    .include(DataComponents.MAX_STACK_SIZE)))));
        }
    }

    static final class BlockTags extends BlockTagsProvider {
        BlockTags(PackOutput output, CompletableFuture<HolderLookup.Provider> lookup, ExistingFileHelper helper) {
            super(output, lookup, LOTRRevival.MOD_ID, helper);
        }

        @Override
        protected void addTags(HolderLookup.Provider provider) {
            tag(net.minecraft.tags.BlockTags.MINEABLE_WITH_AXE).add(BrewingBlocks.BARREL.get());
        }

        @Override
        public String getName() {
            return "Brewing block tags";
        }
    }

    static final class Recipes extends RecipeProvider {
        Recipes(PackOutput output, CompletableFuture<HolderLookup.Provider> registries) {
            super(output, registries);
        }

        @Override
        protected void buildRecipes(RecipeOutput out) {
            ShapedRecipeBuilder.shaped(RecipeCategory.FOOD, BrewingItems.WOODEN_MUG.get(), 2)
                    .pattern("P P")
                    .pattern("PNP")
                    .define('P', ItemTags.PLANKS)
                    .define('N', Items.IRON_NUGGET)
                    .unlockedBy("has_iron_nugget", has(Items.IRON_NUGGET))
                    .save(out);

            ShapedRecipeBuilder.shaped(RecipeCategory.DECORATIONS, BrewingBlocks.BARREL_ITEM.get())
                    .pattern("PPP")
                    .pattern("IBI")
                    .pattern("PPP")
                    .define('P', ItemTags.PLANKS)
                    .define('I', Items.IRON_INGOT)
                    .define('B', Items.BARREL)
                    .unlockedBy("has_barrel", has(Items.BARREL))
                    .save(out);

            brew(out, BrewingItems.ALE.get(), Items.WHEAT, Items.WHEAT, Items.WHEAT, Items.WHEAT, Items.WHEAT, Items.WHEAT);
            brew(out, BrewingItems.CIDER.get(), Items.APPLE, Items.APPLE, Items.APPLE, Items.APPLE, Items.APPLE, Items.APPLE);
            brew(out, BrewingItems.MEAD.get(),
                    Items.HONEYCOMB, Items.HONEYCOMB, Items.HONEYCOMB, Items.HONEYCOMB, Items.HONEYCOMB, Items.HONEYCOMB);
            brew(out, BrewingItems.DWARVEN_TONIC.get(),
                    Items.WHEAT, Items.WHEAT, Items.WHEAT, Items.GLOW_BERRIES, Items.GLOW_BERRIES, Items.IRON_NUGGET);
            brew(out, BrewingItems.MIRUVOR.get(),
                    Items.GOLDEN_APPLE, Items.GLOW_BERRIES, Items.GLOW_BERRIES, Items.HONEYCOMB, Items.HONEYCOMB,
                    Items.SUGAR);
        }

        private static void brew(RecipeOutput out, DrinkItem result, Item... ingredients) {
            List<Ingredient> list = java.util.Arrays.stream(ingredients).map(item -> Ingredient.of(item)).toList();
            ResourceLocation id = LOTRRevival.id("brewing/" + BuiltInRegistries.ITEM.getKey(result).getPath());
            out.accept(id, new BrewingRecipe(list, result), null);
        }
    }
}

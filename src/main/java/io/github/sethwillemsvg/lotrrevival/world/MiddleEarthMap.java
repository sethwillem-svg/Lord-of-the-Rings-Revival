package io.github.sethwillemsvg.lotrrevival.world;

import io.github.sethwillemsvg.lotrrevival.LOTRRevival;
import net.minecraft.resources.ResourceLocation;

/**
 * Canvas, scale and origin of the Middle-earth maps (see {@code specs/world/dimension-and-mapgen.md}).
 *
 * <p>These live in {@code world} until core's shared projection constants land; move them then.
 */
public final class MiddleEarthMap {
    /** Heightmap size in pixels (16-bit grayscale), 64 blocks per pixel. */
    public static final int HEIGHT_WIDTH = 6400;

    public static final int HEIGHT_HEIGHT = 8000;
    public static final int HEIGHT_BLOCKS_PER_PIXEL = 64;

    /** Biome map size in pixels (8-bit RGB key colours), 128 blocks per pixel. */
    public static final int BIOME_WIDTH = 3200;

    public static final int BIOME_HEIGHT = 4000;
    public static final int BIOME_BLOCKS_PER_PIXEL = 128;

    /** Relief map size in pixels (8-bit grayscale, generated by datagen), 256 blocks per pixel. */
    public static final int RELIEF_WIDTH = 1600;

    public static final int RELIEF_HEIGHT = 2000;
    public static final int RELIEF_BLOCKS_PER_PIXEL = 256;

    /** Heightmap pixel (continuous coordinates) that sits at block (0, 0). */
    public static final int ORIGIN_U = 1620;

    public static final int ORIGIN_V = 1460;

    /** Heightmap encoding: y = value * 0.005. */
    public static final double HEIGHT_VERTICAL_SCALE = 0.005;

    /** Relief encoding: value 8 = 1 block of detail amplitude. */
    public static final double RELIEF_VERTICAL_SCALE = 0.125;

    public static final int SEA_LEVEL = 63;

    /** Keys shared by the three map_infos and the images they read. */
    public static final ResourceLocation TERRAIN_INFO = LOTRRevival.id("middle_earth");

    public static final ResourceLocation BIOMES_INFO = LOTRRevival.id("middle_earth_biomes");
    public static final ResourceLocation RELIEF_INFO = LOTRRevival.id("middle_earth_relief");

    /** Image key of the painted heightmap and of the biome map. */
    public static final ResourceLocation HEIGHTMAP_IMAGE = LOTRRevival.id("middle_earth");

    public static final ResourceLocation BIOME_MAP_IMAGE = LOTRRevival.id("middle_earth");
    public static final ResourceLocation RELIEF_IMAGE = LOTRRevival.id("middle_earth_relief");

    private MiddleEarthMap() {}

    /** Heightmap pixel (continuous) to block x. */
    public static double blockX(double u) {
        return HEIGHT_BLOCKS_PER_PIXEL * (u - ORIGIN_U);
    }

    /** Heightmap pixel (continuous) to block z. */
    public static double blockZ(double v) {
        return HEIGHT_BLOCKS_PER_PIXEL * (v - ORIGIN_V);
    }

    /**
     * NovoAtlas {@code center_offset} component that puts block 0 at image index {@code index0}.
     *
     * <p>NovoAtlas shifts the map by {@code offset * imageSize} blocks before dividing by the scale,
     * so {@code offset = (size / 2 - index0) * scale / size}.
     */
    public static float centerOffset(int imageSize, double index0, double blocksPerSample) {
        return (float) ((imageSize / 2.0 - index0) * blocksPerSample / imageSize);
    }

    /** Offset x for the terrain map_info (bicubic samples sit at pixel centres: index u - 0.5). */
    public static float terrainOffsetX() {
        return centerOffset(HEIGHT_WIDTH, ORIGIN_U - 0.5, HEIGHT_BLOCKS_PER_PIXEL);
    }

    public static float terrainOffsetZ() {
        return centerOffset(HEIGHT_HEIGHT, ORIGIN_V - 0.5, HEIGHT_BLOCKS_PER_PIXEL);
    }

    /** Biome map_info: nearest sampling, 32 quarts (128 blocks) per pixel, index = u / 2. */
    public static float biomesOffsetX() {
        return centerOffset(BIOME_WIDTH, ORIGIN_U / 2.0, BIOME_BLOCKS_PER_PIXEL / 4.0);
    }

    public static float biomesOffsetZ() {
        return centerOffset(BIOME_HEIGHT, ORIGIN_V / 2.0, BIOME_BLOCKS_PER_PIXEL / 4.0);
    }

    /** Relief map_info: bilinear, 256 blocks per pixel, index = u / 4 - 0.5. */
    public static float reliefOffsetX() {
        return centerOffset(RELIEF_WIDTH, ORIGIN_U / 4.0 - 0.5, RELIEF_BLOCKS_PER_PIXEL);
    }

    public static float reliefOffsetZ() {
        return centerOffset(RELIEF_HEIGHT, ORIGIN_V / 4.0 - 0.5, RELIEF_BLOCKS_PER_PIXEL);
    }
}

package io.github.sethwillemsvg.lotrrevival.world;

import io.github.sethwillemsvg.lotrrevival.LOTRRevival;
import net.minecraft.resources.ResourceLocation;

/**
 * Canvas, scale and origin of the Middle-earth maps (see {@code specs/world/dimension-and-mapgen.md}).
 *
 * <p>The {@code *_BLOCKS_PER_PIXEL} constants are Legacy scale. The world's actual size depends on its
 * {@link WorldScale}: always convert through {@link #blockX(double, WorldScale)} and friends, never with the
 * constants directly.
 *
 * <p>These live in {@code world} until core's shared projection constants land; move them then.
 */
public final class MiddleEarthMap {
    /** Heightmap size in pixels (16-bit grayscale), 64 blocks per pixel at Legacy scale. */
    public static final int HEIGHT_WIDTH = 6400;

    public static final int HEIGHT_HEIGHT = 8000;
    public static final int HEIGHT_BLOCKS_PER_PIXEL = 64;

    /** Biome map size in pixels (8-bit RGB key colours), 128 blocks per pixel at Legacy scale. */
    public static final int BIOME_WIDTH = 3200;

    public static final int BIOME_HEIGHT = 4000;
    public static final int BIOME_BLOCKS_PER_PIXEL = 128;

    /** Relief map size in pixels (8-bit grayscale, generated by datagen), 256 blocks per pixel at Legacy scale. */
    public static final int RELIEF_WIDTH = 1600;

    public static final int RELIEF_HEIGHT = 2000;
    public static final int RELIEF_BLOCKS_PER_PIXEL = 256;

    /** Heightmap pixel (continuous coordinates) that sits at block (0, 0). */
    public static final int ORIGIN_U = 1620;

    public static final int ORIGIN_V = 1460;

    /** Heightmap encoding: y = value * 0.005. */
    public static final double HEIGHT_VERTICAL_SCALE = 0.005;

    /** Relief encoding: value 8 = 1 block of detail amplitude. */
    public static final double RELIEF_VERTICAL_SCALE = 0.125;

    public static final int SEA_LEVEL = 63;

    /** Keys shared by the three map_infos and the images they read. */
    public static final ResourceLocation TERRAIN_INFO = LOTRRevival.id("middle_earth");

    public static final ResourceLocation BIOMES_INFO = LOTRRevival.id("middle_earth_biomes");
    public static final ResourceLocation RELIEF_INFO = LOTRRevival.id("middle_earth_relief");

    /** Image key of the painted heightmap and of the biome map. */
    public static final ResourceLocation HEIGHTMAP_IMAGE = LOTRRevival.id("middle_earth");

    public static final ResourceLocation BIOME_MAP_IMAGE = LOTRRevival.id("middle_earth");
    public static final ResourceLocation RELIEF_IMAGE = LOTRRevival.id("middle_earth_relief");

    private MiddleEarthMap() {}

    /** Heightmap pixel (continuous) to block x at the running world's scale ({@link WorldScales#current()}). */
    public static double blockX(double u) {
        return blockX(u, WorldScales.current());
    }

    /** Heightmap pixel (continuous) to block z at the running world's scale. */
    public static double blockZ(double v) {
        return blockZ(v, WorldScales.current());
    }

    /** Heightmap pixel (continuous) to block x at {@code scale}. Pixel {@link #ORIGIN_U} is block 0 at every scale. */
    public static double blockX(double u, WorldScale scale) {
        return scale.heightBlocksPerPixel() * (u - ORIGIN_U);
    }

    public static double blockZ(double v, WorldScale scale) {
        return scale.heightBlocksPerPixel() * (v - ORIGIN_V);
    }

    /** Block x to heightmap pixel (continuous) at {@code scale}. Inverse of {@link #blockX(double, WorldScale)}. */
    public static double pixelU(double blockX, WorldScale scale) {
        return ORIGIN_U + blockX / scale.heightBlocksPerPixel();
    }

    public static double pixelV(double blockZ, WorldScale scale) {
        return ORIGIN_V + blockZ / scale.heightBlocksPerPixel();
    }

    /**
     * NovoAtlas {@code center_offset} component that puts block 0 at image index {@code index0}.
     *
     * <p>NovoAtlas shifts the map by {@code offset * imageSize} blocks before dividing by the scale,
     * so {@code offset = (size / 2 - index0) * scale / size}.
     */
    public static float centerOffset(int imageSize, double index0, double blocksPerSample) {
        return (float) ((imageSize / 2.0 - index0) * blocksPerSample / imageSize);
    }

    /** Offset x for the terrain map_info (bicubic samples sit at pixel centres: index u - 0.5). */
    public static float terrainOffsetX(WorldScale scale) {
        return centerOffset(HEIGHT_WIDTH, ORIGIN_U - 0.5, scale.heightBlocksPerPixel());
    }

    public static float terrainOffsetZ(WorldScale scale) {
        return centerOffset(HEIGHT_HEIGHT, ORIGIN_V - 0.5, scale.heightBlocksPerPixel());
    }

    /** Quarts per biome-map pixel: the biome source samples its map per 4-block quart (32, 16 or 8). */
    public static double biomeQuartsPerPixel(WorldScale scale) {
        return scale.biomeBlocksPerPixel() / 4.0;
    }

    /** Biome map_info: nearest sampling, in quarts per pixel, index = u / 2. */
    public static float biomesOffsetX(WorldScale scale) {
        return centerOffset(BIOME_WIDTH, ORIGIN_U / 2.0, biomeQuartsPerPixel(scale));
    }

    public static float biomesOffsetZ(WorldScale scale) {
        return centerOffset(BIOME_HEIGHT, ORIGIN_V / 2.0, biomeQuartsPerPixel(scale));
    }

    /** Relief map_info: bilinear, index = u / 4 - 0.5. */
    public static float reliefOffsetX(WorldScale scale) {
        return centerOffset(RELIEF_WIDTH, ORIGIN_U / 4.0 - 0.5, scale.reliefBlocksPerPixel());
    }

    public static float reliefOffsetZ(WorldScale scale) {
        return centerOffset(RELIEF_HEIGHT, ORIGIN_V / 4.0 - 0.5, scale.reliefBlocksPerPixel());
    }
}

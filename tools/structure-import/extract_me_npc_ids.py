#!/usr/bin/env python3
"""Lists Middle-earth's faction ids and NPC type ids (with each type's faction id), read from its source tree.

    python3 -I tools/structure-import/extract_me_npc_ids.py <middle-earth source> [--out me_npc_ids.json]

Ids only (integration points, no other data). Our resident pools in
``addon/src/main/resources/data/lotr_revival/middle-earth/structure_manager_data/`` name these ids; the Python tests
check every pool against this list, and the GameTest ``PoolTests`` checks them again against the live registries.

Found as:
- factions: the keys of Middle-earth's faction registry class, built from one path or a parent path plus a child,
  joined with ``.``;
- NPC types: the keys of its NPC type registry class (faction path ``.`` type name), kept only when an NPC type pool
  that the registry's bootstrap registers lists the key; the type's faction is that pool's faction.
Standard library only.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))      # python -I leaves the script's folder off the path

from extract_me_block_ids import ExtractError, java_root, source_revision, strip_comments  # noqa: E402

NS = "middle-earth"
FACTIONS = "registries/content/factions/FactionRegistry.java"
NPC_REGISTRY = "registries/content/npctypes/NpcRegistry.java"
NPC_POOLS = "registries/content/npctypes/pools"


def factions(src: str) -> dict:
    """Constant name -> faction path."""
    out = {}
    for m in re.finditer(r"ResourceKey<Faction>\s+([A-Z_]+)\s*=\s*\w+\.of\(\s*\w+\s*,\s*MiddleEarth\.of\((.*?)\)\s*\)\s*;", src):
        parts = []
        for arg in m.group(2).split(","):
            arg = arg.strip()
            lit = re.fullmatch(r"\"([a-z0-9_]+)\"", arg)
            ref = re.fullmatch(r"([A-Z_]+)\.location\(\)\.getPath\(\)", arg)
            if lit:
                parts.append(lit.group(1))
            elif ref and ref.group(1) in out:
                parts.append(out[ref.group(1)])
            else:
                raise ExtractError(f"cannot read faction {m.group(1)}: {arg}")
        out[m.group(1)] = ".".join(parts)
    if not out:
        raise ExtractError("no factions found")
    return out


def npc_types(root: Path) -> tuple[dict, dict]:
    """(faction id -> True, npc type id -> faction id)."""
    fac = factions(strip_comments((root / FACTIONS).read_text(encoding="utf-8")))
    reg = strip_comments((root / NPC_REGISTRY).read_text(encoding="utf-8"))
    keys = {}
    for m in re.finditer(r"ResourceKey<NpcType>\s+([A-Z_]+)\s*=\s*[\w.]+\.of\(\s*\w+\s*,\s*createID\(\s*FactionRegistry\.([A-Z_]+)\s*,"
                         r"\s*\"([a-z0-9_]+)\"\s*\)\s*\)", reg):
        if m.group(2) not in fac:
            raise ExtractError(f"NPC key {m.group(1)} names unknown faction {m.group(2)}")
        keys[m.group(1)] = f"{fac[m.group(2)]}.{m.group(3)}"
    boot = re.search(r"\bvoid\s+bootstrap\s*\(", reg)
    if not boot:
        raise ExtractError("no NPC type bootstrap")
    registered_pools = re.findall(r"registerAll\([^;]*?\b(\w+NpcTypePool)\.fetchAll\(\)", reg[boot.start():])
    types = {}
    for pool in registered_pools:
        p = root / NPC_POOLS / f"{pool}.java"
        s = strip_comments(p.read_text(encoding="utf-8"))
        f = re.search(r"ResourceKey<Faction>\s+FACTION\s*=\s*FactionRegistry\.([A-Z_]+)", s)
        if not f:
            raise ExtractError(f"{pool}: no FACTION")
        fetch = re.search(r"fetchAll\s*\(\s*\)\s*\{(.*?)\}", s, re.S)
        if not fetch:
            raise ExtractError(f"{pool}: no fetchAll")
        for key in re.findall(r"RegisterableNpcData\(\s*NpcRegistry\.([A-Z_]+)", fetch.group(1)):
            if key not in keys:
                raise ExtractError(f"{pool}: unknown NPC key {key}")
            types[f"{NS}:{keys[key]}"] = f"{NS}:{fac[f.group(1)]}"
    if not types:
        raise ExtractError("no NPC types found")
    return {f"{NS}:{v}": True for v in fac.values()}, types


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("source", type=Path, help="Middle-earth source checkout (read only)")
    ap.add_argument("--out", type=Path, default=HERE / "me_npc_ids.json")
    a = ap.parse_args(argv)
    try:
        facs, types = npc_types(java_root(a.source))
    except (ExtractError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    rev = source_revision(a.source)
    out = {
        "description": "Faction ids and NPC type ids (with each type's faction id) Middle-earth registers; ids only. "
                       "Generated by tools/structure-import/extract_me_npc_ids.py; do not edit by hand.",
        "source": "Middle-earth (Jukoz), branch neoforge-fixes" + (f", commit {rev}" if rev else ""),
        "factions": sorted(facs),
        "npc_types": dict(sorted(types.items())),
    }
    a.out.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {a.out} ({len(facs)} factions, {len(types)} NPC types)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

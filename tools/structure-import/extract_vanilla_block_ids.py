#!/usr/bin/env python3
"""Writes ``vanilla_block_ids.json``: the block ids of vanilla Minecraft 1.21.1 (ids only).

    python3 -I tools/structure-import/extract_vanilla_block_ids.py <blocks.json> [--out vanilla_block_ids.json]

<blocks.json> is ``data/pc/1.21.1/blocks.json`` from PrismarineJS minecraft-data (MIT licence,
https://github.com/PrismarineJS/minecraft-data). Only each entry's ``name`` is read. The palettes, templates and
``import.py verify`` check vanilla ids against this list (specs/addon/structures.md, Palette remapping); properties still
come from the block dump. Standard library only.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
VERSION = "1.21.1"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("blocks", type=Path, help=f"minecraft-data data/pc/{VERSION}/blocks.json")
    ap.add_argument("--out", type=Path, default=HERE / "vanilla_block_ids.json")
    a = ap.parse_args(argv)
    data = json.loads(a.blocks.read_text(encoding="utf-8"))
    names = sorted({b["name"] for b in data})
    bad = [n for n in names if not re.fullmatch(r"[a-z0-9_]+", n)]
    if bad or "air" not in names:
        print(f"error: not a block list: {bad[:5]}", file=sys.stderr)
        return 1
    out = {
        "description": f"Block registry ids of vanilla Minecraft {VERSION} (ids only). Generated by "
                       "tools/structure-import/extract_vanilla_block_ids.py; do not edit by hand.",
        "source": f"PrismarineJS minecraft-data (MIT), data/pc/{VERSION}/blocks.json, names only",
        "version": VERSION,
        "count": len(names),
        "ids": [f"minecraft:{n}" for n in names],
    }
    a.out.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {a.out} ({len(names)} ids)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

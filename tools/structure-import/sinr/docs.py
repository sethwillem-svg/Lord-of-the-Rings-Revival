"""The readable licence log (docs/licences/structures.md) and the NOTICE credits block."""
from __future__ import annotations

from . import emit, licences

BEGIN = "# BEGIN structure credits (generated by tools/structure-import)"
END = "# END structure credits"
EXCEPTION = ("Structure templates under `data/lotr_revival/structure/build/` are not covered by ASSETS_LICENSE; "
             "each keeps the licence listed here.")


def standard_line(m: dict) -> str:
    if m.get("attribution"):
        return m["attribution"]
    if m.get("own_work"):
        return f'"{m["title"]}" by {m["author"]}, own work for LOTR Revival, under {licences.name(licences.OWN)}.'
    if m["licence"] == "CC0-1.0":
        return f'"{m["title"]}" by {m["author"]} ({m["source_url"]}), CC0.'
    lic = m["licence"]
    return (f'"{m["title"]}" by {m["author"]} ({m["source_url"]}) is licensed under {licences.name(lic)} '
            f'({m.get("licence_url") or licences.url(lic)}). Modified for LOTR Revival: {emit.changes_summary(m)}. '
            "The author does not endorse this mod.")


def _cell(v) -> str:
    if v is None or v == "" or v == []:
        return "-"
    if isinstance(v, list):
        v = "; ".join(str(x) for x in v)
    return str(v).replace("|", "\\|").replace("\n", " ")


def licence_log(manifests: list) -> str:
    lines = [
        "# Structure licence log",
        "",
        "Generated by `tools/structure-import` (`python3 -I tools/structure-import/import.py docs`) from the manifests in",
        "`tools/structure-import/builds/*/build.json`. Do not edit by hand. Rules: `specs/addon/structures.md`.",
        "",
        "| id | status | title | author | source | archive | licence | retrieved | approved | changes | output | output licence |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for m in sorted(manifests, key=lambda x: x["id"]):
        approved = f"{m.get('approved_by')} {m.get('approved_on')}" if m.get("approved_by") else ("own work" if m.get("own_work") else None)
        changes = emit.changes_summary(m)
        if m.get("status") in ("rejected", "withdrawn") and m.get("notes"):
            changes = (changes + "; " if changes else "") + f"{m['status']}: {m['notes']}"
        out_lic = m.get("output_licence") or (licences.output_licence(m["licence"]) if licences.refusal_reason(m["licence"]) is None
                                              or m["licence"] == licences.OWN else None)
        lines.append("| " + " | ".join(_cell(v) for v in (
            f"`{m['id']}`", m.get("status"), m.get("title"), m.get("author"), m.get("source_url"), m.get("archive_url"),
            licences.name(m["licence"]), m.get("retrieved"), approved, changes,
            f"`{m['output']}`" if m.get("status") not in ("rejected", "withdrawn", "candidate") else None, out_lic and licences.name(out_lic),
        )) + " |")
    lines.append("")
    return "\n".join(lines)


def notice_block(manifests: list) -> str:
    lines = [BEGIN, EXCEPTION, ""]
    for m in sorted(manifests, key=lambda x: x["id"]):
        lic = m.get("output_licence") or licences.output_licence(m["licence"])
        lines.append(f'"{m["title"]}" ({m["id"]})')
        lines.append(f"  Author:   {m['author']}")
        if m.get("source_url"):
            lines.append(f"  Source:   {m['source_url']}")
        if not m.get("own_work"):
            lines.append(f"  Licence:  {licences.name(m['licence'])} ({m.get('licence_url') or licences.url(m['licence'])})")
            lines.append(f"  Modified: {emit.changes_summary(m)}")
        lines.append(f"  Our template's licence: {licences.name(lic)}")
        lines.append(f"  Credit:   {standard_line(m)}")
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def replace_notice(text: str, block: str) -> str:
    """Replaces the block between the markers (or appends it); nothing else in NOTICE changes."""
    start = text.find(BEGIN)
    if start >= 0:
        end = text.find(END, start)
        if end < 0:
            raise ValueError("NOTICE has the BEGIN marker but no END marker")
        return text[:start] + block + text[end + len(END):]
    sep = "" if text.endswith("\n\n") else ("\n" if text.endswith("\n") else "\n\n")
    return text + sep + block + "\n"
